// ========================================================================
// SDF Studio 3D - Standalone GLSL Shader Code Exporter (Shadertoy & Three.js)
// Compiles the interactive CSG AST into clean, optimized GLSL shader code.
// ========================================================================

import { CSGTree } from '../tree/CSGTree';
import { PrimitiveType } from '../tree/types';

export class ShaderExporter {
  /**
   * Generates a fully self-contained Shadertoy-compatible GLSL fragment shader.
   * Paste directly into shadertoy.com to render the exact CSG scene in real-time.
   */
  public static exportShadertoy(tree: CSGTree): string {
    const flattened = tree.flattenWithTransforms();

    const lines: string[] = [];
    lines.push('// ========================================================================');
    lines.push('// Generated by SDF Studio 3D - Standalone Shadertoy Fragment Shader');
    lines.push(`// Generated At: ${new Date().toISOString()}`);
    lines.push(`// Total Primitives: ${flattened.length}`);
    lines.push('// ========================================================================');
    lines.push('');
    lines.push('// --- PRIMITIVES LIBRARY ---');
    lines.push('float sdSphere(vec3 p, float r) { return length(p) - r; }');
    lines.push('float sdBox(vec3 p, vec3 b) { vec3 q = abs(p) - b; return length(max(q, 0.0)) + min(max(q.x, max(q.y, q.z)), 0.0); }');
    lines.push('float sdRoundBox(vec3 p, vec3 b, float r) { vec3 q = abs(p) - b + r; return length(max(q, 0.0)) + min(max(q.x, max(q.y, q.z)), 0.0) - r; }');
    lines.push('float sdCappedCylinder(vec3 p, float h, float r) { vec2 d = abs(vec2(length(p.xz), p.y)) - vec2(r, h); return min(max(d.x, d.y), 0.0) + length(max(d, 0.0)); }');
    lines.push('float sdTorus(vec3 p, float R, float r) { vec2 q = vec2(length(p.xz) - R, p.y); return length(q) - r; }');
    lines.push('float sdCapsule(vec3 p, float h, float r) { p.y -= clamp(p.y, -h, h); return length(p) - r; }');
    lines.push('float sdCappedCone(vec3 p, float h, float r1, float r2) {');
    lines.push('    vec2 q = vec2(length(p.xz), p.y);');
    lines.push('    vec2 k1 = vec2(r2, h); vec2 k2 = vec2(r2 - r1, 2.0 * h);');
    lines.push('    vec2 ca = vec2(q.x - min(q.x, (q.y < 0.0) ? r1 : r2), abs(q.y) - h);');
    lines.push('    vec2 cb = q - k1 + k2 * clamp(dot(k1 - q, k2) / dot(k2, k2), 0.0, 1.0);');
    lines.push('    float s = (cb.x < 0.0 && ca.y < 0.0) ? -1.0 : 1.0;');
    lines.push('    return s * sqrt(min(dot(ca, ca), dot(cb, cb)));');
    lines.push('}');
    lines.push('float sdPlane(vec3 p, vec3 n, float h) { return dot(p, normalize(n)) + h; }');
    lines.push('float sdPipe(vec3 p, float h, float r, float th) { float d1 = length(p.xz) - r; vec2 w = vec2(abs(d1) - th, abs(p.y) - h); return min(max(w.x, w.y), 0.0) + length(max(w, 0.0)); }');
    lines.push('float sdHemisphere(vec3 p, float r) { return max(length(p) - r, -p.y); }');
    lines.push('float sdEllipsoid(vec3 p, vec3 r) { float k0 = length(p / r); float k1 = length(p / (r * r)); return k0 * (k0 - 1.0) / max(k1, 0.0001); }');
    lines.push('float sdTriangularPrism(vec3 p, vec2 h) { vec3 q = abs(p); return max(q.z - h.y, max(q.x * 0.866025 + p.y * 0.5, -p.y) - h.x * 0.5); }');
    lines.push('float sdHexagonalPrism(vec3 p, vec2 h) { const vec3 k = vec3(-0.8660254, 0.5, 0.57735); p = abs(p); p.xy -= 2.0 * min(dot(k.xy, p.xy), 0.0) * k.xy; vec2 d = vec2(length(p.xy - vec2(clamp(p.x, -k.z * h.x, k.z * h.x), h.x)) * sign(p.y - h.x), p.z - h.y); return min(max(d.x, d.y), 0.0) + length(max(d, 0.0)); }');
    lines.push('float sdOctahedron(vec3 p, float s) { p = abs(p); float m = p.x + p.y + p.z - s; vec3 q; if (3.0 * p.x < m) q = p.xyz; else if (3.0 * p.y < m) q = p.yzx; else if (3.0 * p.z < m) q = p.zxy; else return m * 0.57735027; float k = clamp(0.5 * (q.z - q.y + s), 0.0, s); return length(vec3(q.x, q.y - s + k, q.z - k)); }');
    lines.push('float sdTetrahedron(vec3 p, float r) { const vec3 n1 = vec3(0.57735, 0.57735, 0.57735); const vec3 n2 = vec3(-0.57735, -0.57735, 0.57735); const vec3 n3 = vec3(-0.57735, 0.57735, -0.57735); const vec3 n4 = vec3(0.57735, -0.57735, -0.57735); float d1 = dot(p, n1); float d2 = dot(p, n2); float d3 = dot(p, n3); float d4 = dot(p, n4); return max(max(d1, d2), max(d3, d4)) - r; }');
    lines.push('float sdMandelbulb(vec3 p) { vec3 w = p; float m = dot(w, w); float dz = 1.0; for (int i = 0; i < 4; i++) { dz = 8.0 * pow(m, 3.5) * dz + 1.0; float r = length(w); float b = 8.0 * acos(clamp(w.y / r, -1.0, 1.0)); float a = 8.0 * atan(w.x, w.z); w = p + pow(r, 8.0) * vec3(sin(b) * sin(a), cos(b), sin(b) * cos(a)); m = dot(w, w); if (m > 256.0) break; } return 0.25 * log(m) * sqrt(m) / dz; }');
    lines.push('');
    lines.push('// --- CSG BOOLEAN OPERATIONS ---');
    lines.push('float sminPoly(float a, float b, float k) { if (k <= 0.0001) return min(a, b); float h = clamp(0.5 + 0.5 * (b - a) / k, 0.0, 1.0); return mix(b, a, h) - k * h * (1.0 - h); }');
    lines.push('float smaxPoly(float a, float b, float k) { return -sminPoly(-a, -b, k); }');
    lines.push('float opUnion(float d1, float d2, float k, bool smoothOp) { return smoothOp ? sminPoly(d1, d2, k) : min(d1, d2); }');
    lines.push('float opDiff(float d1, float d2, float k, bool smoothOp) { return smoothOp ? smaxPoly(d1, -d2, k) : max(d1, -d2); }');
    lines.push('float opInter(float d1, float d2, float k, bool smoothOp) { return smoothOp ? smaxPoly(d1, d2, k) : max(d1, d2); }');
    lines.push('');
    lines.push('// --- SCENE DISTANCE FIELD MAP ---');
    lines.push('float map(vec3 worldPos) {');
    lines.push('    float totalDist = 1e5;');
    lines.push('');

    // Generate code for each primitive
    flattened.forEach((item, index) => {
      const node = item.node;
      const invM = item.inverseWorldMatrix.elements;
      const pVar = `p_${index}`;
      const dVar = `d_${index}`;

      lines.push(`    // Node ${index}: ${node.name} (${node.primitive.type})`);
      lines.push(`    mat4 invMat_${index} = mat4(`);
      lines.push(`        ${invM[0].toFixed(5)}, ${invM[1].toFixed(5)}, ${invM[2].toFixed(5)}, ${invM[3].toFixed(5)},`);
      lines.push(`        ${invM[4].toFixed(5)}, ${invM[5].toFixed(5)}, ${invM[6].toFixed(5)}, ${invM[7].toFixed(5)},`);
      lines.push(`        ${invM[8].toFixed(5)}, ${invM[9].toFixed(5)}, ${invM[10].toFixed(5)}, ${invM[11].toFixed(5)},`);
      lines.push(`        ${invM[12].toFixed(5)}, ${invM[13].toFixed(5)}, ${invM[14].toFixed(5)}, ${invM[15].toFixed(5)}`);
      lines.push(`    );`);
      lines.push(`    vec3 ${pVar} = (invMat_${index} * vec4(worldPos, 1.0)).xyz;`);

      // Apply Modifiers
      const mods = node.modifiers || {};
      if (mods.mirrorAxis && mods.mirrorAxis !== 'none') {
        lines.push(`    ${pVar}.${mods.mirrorAxis} = abs(${pVar}.${mods.mirrorAxis});`);
      }
      const twistFactor = mods.twistFactor ?? mods.twist ?? 0.0;
      if (Math.abs(twistFactor) > 0.001) {
        lines.push(`    float c_${index} = cos(${twistFactor.toFixed(4)} * ${pVar}.y);`);
        lines.push(`    float s_${index} = sin(${twistFactor.toFixed(4)} * ${pVar}.y);`);
        lines.push(`    ${pVar}.xz = mat2(c_${index}, -s_${index}, s_${index}, c_${index}) * ${pVar}.xz;`);
      }

      // Primitive call
      const primCall = ShaderExporter.generatePrimitiveCall(node.primitive.type, pVar, node.primitive.dimensions);
      lines.push(`    float ${dVar} = ${primCall};`);

      // Shell & Rounding modifiers
      if (mods.roundRadius && mods.roundRadius > 0.001) {
        lines.push(`    ${dVar} -= ${mods.roundRadius.toFixed(4)};`);
      }
      if (mods.shellThickness && mods.shellThickness > 0.001) {
        lines.push(`    ${dVar} = abs(${dVar}) - ${mods.shellThickness.toFixed(4)};`);
      }

      // CSG accumulation
      const isSmooth = node.csg.blendMode === 'smooth_polynomial' && node.csg.blendRadius > 0.0001;
      const k = node.csg.blendRadius.toFixed(4);
      const isSmoothStr = isSmooth ? 'true' : 'false';

      if (index === 0) {
        lines.push(`    totalDist = ${dVar};`);
      } else {
        if (node.csg.operation === 'difference') {
          lines.push(`    totalDist = opDiff(totalDist, ${dVar}, ${k}, ${isSmoothStr});`);
        } else if (node.csg.operation === 'intersection') {
          lines.push(`    totalDist = opInter(totalDist, ${dVar}, ${k}, ${isSmoothStr});`);
        } else {
          lines.push(`    totalDist = opUnion(totalDist, ${dVar}, ${k}, ${isSmoothStr});`);
        }
      }
      lines.push('');
    });

    lines.push('    return totalDist;');
    lines.push('}');
    lines.push('');
    lines.push('// --- NORMAL GRADIENT CALCULATION ---');
    lines.push('vec3 calcNormal(vec3 p) {');
    lines.push('    const float eps = 0.001;');
    lines.push('    const vec2 h = vec2(eps, 0.0);');
    lines.push('    return normalize(vec3(');
    lines.push('        map(p + h.xyy) - map(p - h.xyy),');
    lines.push('        map(p + h.yxy) - map(p - h.yxy),');
    lines.push('        map(p + h.yyx) - map(p - h.yyx)');
    lines.push('    ));');
    lines.push('}');
    lines.push('');
    lines.push('// --- RAYMARCHING LOOP ---');
    lines.push('float raymarch(vec3 ro, vec3 rd) {');
    lines.push('    float t = 0.01;');
    lines.push('    for (int i = 0; i < 128; i++) {');
    lines.push('        vec3 p = ro + rd * t;');
    lines.push('        float d = map(p);');
    lines.push('        if (d < 0.001) return t;');
    lines.push('        if (t > 40.0) break;');
    lines.push('        t += d;');
    lines.push('    }');
    lines.push('    return -1.0;');
    lines.push('}');
    lines.push('');
    lines.push('// --- SHADERTOY MAIN ENTRYPOINT ---');
    lines.push('void mainImage(out vec4 fragColor, in vec2 fragCoord) {');
    lines.push('    vec2 uv = (fragCoord.xy - 0.5 * iResolution.xy) / iResolution.y;');
    lines.push('');
    lines.push('    // Orbiting Camera');
    lines.push('    float angle = iTime * 0.4;');
    lines.push('    if (iMouse.z > 0.0) angle = (iMouse.x / iResolution.x) * 6.2831;');
    lines.push('    vec3 ro = vec3(3.2 * sin(angle), 1.8, 3.2 * cos(angle));');
    lines.push('    vec3 target = vec3(0.0, 0.0, 0.0);');
    lines.push('    vec3 ww = normalize(target - ro);');
    lines.push('    vec3 uu = normalize(cross(ww, vec3(0.0, 1.0, 0.0)));');
    lines.push('    vec3 vv = cross(uu, ww);');
    lines.push('    vec3 rd = normalize(uv.x * uu + uv.y * vv + 1.6 * ww);');
    lines.push('');
    lines.push('    // Background Gradient');
    lines.push('    vec3 col = mix(vec3(0.08, 0.09, 0.11), vec3(0.03, 0.03, 0.04), clamp(uv.y + 0.5, 0.0, 1.0));');
    lines.push('');
    lines.push('    // Raymarch Scene');
    lines.push('    float t = raymarch(ro, rd);');
    lines.push('    if (t > 0.0) {');
    lines.push('        vec3 p = ro + rd * t;');
    lines.push('        vec3 n = calcNormal(p);');
    lines.push('        vec3 lightDir = normalize(vec3(0.8, 1.2, 0.6));');
    lines.push('');
    lines.push('        // Key + Fill Shading');
    lines.push('        float diff = max(dot(n, lightDir), 0.0);');
    lines.push('        float fill = max(dot(n, -lightDir), 0.0) * 0.25;');
    lines.push('        float ambient = 0.15;');
    lines.push('        vec3 viewDir = -rd;');
    lines.push('        vec3 halfDir = normalize(lightDir + viewDir);');
    lines.push('        float spec = pow(max(dot(n, halfDir), 0.0), 32.0) * 0.4;');
    lines.push('');
    lines.push('        vec3 albedo = vec3(0.88, 0.90, 0.94);');
    lines.push('        col = albedo * (diff + fill + ambient) + vec3(spec);');
    lines.push('    }');
    lines.push('');
    lines.push('    // Gamma Correction');
    lines.push('    col = pow(col, vec3(1.0 / 2.2));');
    lines.push('    fragColor = vec4(col, 1.0);');
    lines.push('}');

    return lines.join('\n');
  }

  private static generatePrimitiveCall(type: PrimitiveType, pVar: string, dims: any): string {
    switch (type) {
      case 'sphere':
        return `sdSphere(${pVar}, ${(dims.radius ?? 0.8).toFixed(4)})`;
      case 'box': {
        const s = dims.size || [0.7, 0.7, 0.7];
        return `sdBox(${pVar}, vec3(${s[0].toFixed(4)}, ${s[1].toFixed(4)}, ${s[2].toFixed(4)}))`;
      }
      case 'cylinder':
        return `sdCappedCylinder(${pVar}, ${(dims.height ?? 0.8).toFixed(4)}, ${(dims.radius ?? 0.5).toFixed(4)})`;
      case 'torus':
        return `sdTorus(${pVar}, ${(dims.radiusMajor ?? 0.7).toFixed(4)}, ${(dims.radiusMinor ?? 0.25).toFixed(4)})`;
      case 'capsule':
        return `sdCapsule(${pVar}, ${(dims.height ?? 0.8).toFixed(4)}, ${(dims.radius ?? 0.4).toFixed(4)})`;
      case 'cone':
        return `sdCappedCone(${pVar}, ${(dims.height ?? 0.8).toFixed(4)}, ${(dims.baseRadius ?? 0.6).toFixed(4)}, ${(dims.topRadius ?? 0.2).toFixed(4)})`;
      case 'plane':
        return `sdPlane(${pVar}, vec3(0.0, 1.0, 0.0), 0.0)`;
      case 'pipe':
        return `sdPipe(${pVar}, ${(dims.height ?? 0.8).toFixed(4)}, ${(dims.radius ?? 0.6).toFixed(4)}, ${(dims.thickness ?? 0.08).toFixed(4)})`;
      case 'hemisphere':
        return `sdHemisphere(${pVar}, ${(dims.radius ?? 0.8).toFixed(4)})`;
      case 'ellipsoid': {
        const r = dims.radii || [0.8, 0.5, 0.5];
        return `sdEllipsoid(${pVar}, vec3(${r[0].toFixed(4)}, ${r[1].toFixed(4)}, ${r[2].toFixed(4)}))`;
      }
      case 'triangular_prism':
        return `sdTriangularPrism(${pVar}, vec2(${(dims.radius ?? 0.6).toFixed(4)}, ${(dims.height ?? 0.8).toFixed(4)}))`;
      case 'hexagonal_prism':
        return `sdHexagonalPrism(${pVar}, vec2(${(dims.radius ?? 0.6).toFixed(4)}, ${(dims.height ?? 0.8).toFixed(4)}))`;
      case 'octahedron':
        return `sdOctahedron(${pVar}, ${(dims.radius ?? 0.8).toFixed(4)})`;
      case 'tetrahedron':
        return `sdTetrahedron(${pVar}, ${(dims.radius ?? 0.8).toFixed(4)})`;
      case 'mandelbulb':
        return `sdMandelbulb(${pVar})`;
      default:
        return `sdSphere(${pVar}, 0.8)`;
    }
  }
}
